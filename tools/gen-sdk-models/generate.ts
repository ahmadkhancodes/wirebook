import { OBJECTS } from '../../src/lib/v1/objects';
import { OPS, address, keyOf, ref, type Field, type Spec } from '../../src/lib/qbxml/spec';

/**
 * Typed SDK models for every API object, generated from the same field specs the API validates with
 * (src/lib/qbxml/spec.ts), so a field added to a spec shows up in both SDKs after `npm run gen:sdk`.
 * A test (tests/sdk-models.test.ts) fails when the committed files are out of date.
 *
 * Per object: `<Name>Create` (required fields required), `<Name>Update` (revisionNumber required, the id is the path
 * argument and is left out) and `<Name>` (a row: every field optional, rows stay open to fields the specs do not list).
 */

/** Singular PascalCase type name per URL segment. Add a row here when a new object is added to OBJECTS. */
export const TYPE_NAMES: Record<string, string> = {
  customers: 'Customer', vendors: 'Vendor', items: 'Item', accounts: 'Account', invoices: 'Invoice', bills: 'Bill', payments: 'Payment',
  estimates: 'Estimate', 'sales-orders': 'SalesOrder', 'sales-receipts': 'SalesReceipt', 'credit-memos': 'CreditMemo',
  'purchase-orders': 'PurchaseOrder', classes: 'QbClass', terms: 'Term', employees: 'Employee',
};

const pascal = (s: string) => s.replace(/^./, (c) => c.toUpperCase());
const singular = (s: string) => (s.endsWith('ies') ? `${s.slice(0, -3)}y` : s.endsWith('s') ? s.slice(0, -1) : s);
const same = (a: Spec | undefined, b: Spec) => JSON.stringify(a) === JSON.stringify(b);

interface Iface { name: string; fields: Field[]; /** fields in this list are made optional (rows) */ allOptional: boolean }

class Collector {
  readonly ifaces = new Map<string, Iface>();
  /** Returns the named type for an obj or list field with children, registering its interface. */
  named(owner: string, f: Field, allOptional: boolean): string {
    if (same(f.children, ref)) return 'Ref';
    if (same(f.children, address)) return 'Address';
    const base = f.kind === 'list' ? singular(pascal(keyOf(f))) : pascal(keyOf(f));
    const name = `${owner}${base}`;
    if (!this.ifaces.has(name)) {
      this.ifaces.set(name, { name, fields: [], allOptional });
      this.ifaces.get(name)!.fields = [...(f.children ?? [])];
    }
    return name;
  }
}

export interface Model { object: string; type: string; create: Spec; update?: Spec; idKey: 'listId' | 'txnId' }

export function models(): Model[] {
  return Object.entries(OBJECTS).map(([object, def]) => {
    const type = TYPE_NAMES[object];
    if (!type) throw new Error(`gen-sdk-models: add "${object}" to TYPE_NAMES`);
    return { object, type, create: OPS[def.add].spec, update: def.mod ? OPS[def.mod].spec : undefined, idKey: def.idList === 'txnIds' ? 'txnId' : 'listId' };
  });
}

type Lang = { scalar(k: Field['kind']): string; list(t: string): string; ref(f: Field, t: string): string };

/** One interface body: [key, required, type]. */
function rows(spec: Spec, owner: string, c: Collector, opts: { allOptional: boolean; omit?: string[] }): { key: string; required: boolean; kind: Field['kind']; type?: string; list: boolean }[] {
  return spec.filter((f) => !opts.omit?.includes(keyOf(f))).map((f) => {
    const withChildren = (f.kind === 'obj' || f.kind === 'list') && f.children && f.children.length > 0;
    return {
      key: keyOf(f),
      required: !opts.allOptional && !!f.required,
      kind: f.kind,
      list: f.kind === 'list',
      type: withChildren ? c.named(owner, f, opts.allOptional) : undefined,
    };
  });
}

/** Collect every nested interface (depth first) for a spec under an owner prefix. */
function collect(spec: Spec, owner: string, c: Collector, allOptional: boolean) {
  for (const f of spec) {
    if ((f.kind === 'obj' || f.kind === 'list') && f.children && f.children.length > 0) {
      const n = c.named(owner, f, allOptional);
      if (n !== 'Ref' && n !== 'Address') collect(f.children, n, c, allOptional);
    }
  }
}

const header = (comment: string) => `${comment}\n`;

export function generateTs(): string {
  const ts: Lang = {
    scalar: (k) => ({ str: 'string', amount: 'number | string', price: 'number | string', quan: 'number | string', int: 'number', bool: 'boolean', date: 'string', obj: 'unknown', list: 'unknown' })[k],
    list: (t) => `${t}[]`,
    ref: (_f, t) => t,
  };
  const out: string[] = [];
  const ty = (r: ReturnType<typeof rows>[number]) => (r.type ? (r.list ? ts.list(r.type) : r.type) : r.list ? 'string[]' : ts.scalar(r.kind));
  const emit = (name: string, extend: string | null, list: ReturnType<typeof rows>, extra: string[] = []) => {
    out.push(`export interface ${name}${extend ? ` extends ${extend}` : ''} {`);
    for (const l of extra) out.push(`  ${l}`);
    for (const r of list) out.push(`  ${r.key}${r.required ? '' : '?'}: ${ty(r)};`);
    out.push('}');
  };

  out.push(header('// GENERATED by tools/gen-sdk-models from src/lib/qbxml/spec.ts. Do not edit; run `npm run gen:sdk`.'));
  out.push("import type { QbRecord } from './types.js';\n");
  const fieldsRef = ref.map((f) => ({ key: keyOf(f), required: false, kind: f.kind, list: false }));
  const fieldsAddr = address.map((f) => ({ key: keyOf(f), required: false, kind: f.kind, list: false }));
  emit('Ref', null, fieldsRef, []);
  out.push('');
  emit('Address', null, fieldsAddr, []);
  for (const m of models()) {
    // shared nested types: created from the Create spec (rows use them too), then update-only ones
    const cc = new Collector();
    collect(m.create, m.type, cc, false);
    for (const i of cc.ifaces.values()) {
      out.push('');
      emit(i.name, null, rows(i.fields, i.name, cc, { allOptional: false }));
    }
    out.push('');
    emit(`${m.type}Create`, null, rows(m.create, m.type, cc, { allOptional: false }));
    out.push('');
    emit(m.type, 'QbRecord', rows(m.create, m.type, cc, { allOptional: true }));
    if (m.update) {
      const cu = new Collector();
      const owner = `${m.type}Update`;
      collect(m.update, owner, cu, false);
      for (const i of cu.ifaces.values()) {
        out.push('');
        emit(i.name, null, rows(i.fields, i.name, cu, { allOptional: false }));
      }
      out.push('');
      emit(owner, null, rows(m.update, owner, cu, { allOptional: false, omit: [m.idKey] }));
    }
  }
  out.push('');
  out.push('/** Every API object: URL segment, the model names and whether it can be updated. */');
  out.push('export const MODELS = {');
  for (const m of models()) out.push(`  '${m.object}': { type: '${m.type}', idKey: '${m.idKey}', updatable: ${m.update ? 'true' : 'false'} },`);
  out.push('} as const;');
  return `${out.join('\n')}\n`;
}

const PY_KEYWORDS = new Set(['class', 'def', 'from', 'import', 'in', 'is', 'lambda', 'not', 'or', 'pass', 'raise', 'return', 'try', 'while', 'with', 'yield', 'global', 'if', 'else', 'for', 'and', 'as', 'del', 'None', 'True', 'False']);

export function generatePy(): string {
  const scalar = (k: Field['kind']) => ({ str: 'str', amount: 'Number', price: 'Number', quan: 'Number', int: 'int', bool: 'bool', date: 'str', obj: 'Any', list: 'Any' })[k];
  const out: string[] = [];
  const ty = (r: ReturnType<typeof rows>[number]) => (r.type ? (r.list ? `List[${r.type}]` : r.type) : r.list ? 'List[str]' : scalar(r.kind));
  /** TypedDict with required keys split into a private base (typing_extensions is not needed on 3.9). */
  const emit = (name: string, list: ReturnType<typeof rows>, extra: { key: string; type: string }[] = []) => {
    for (const r of list) if (PY_KEYWORDS.has(r.key)) throw new Error(`gen-sdk-models: ${r.key} is a Python keyword`);
    const req = list.filter((r) => r.required);
    const opt = [...extra.map((e) => ({ key: e.key, text: e.type })), ...list.filter((r) => !r.required).map((r) => ({ key: r.key, text: ty(r) }))];
    if (req.length > 0) {
      out.push(`class _${name}Required(TypedDict):`);
      for (const r of req) out.push(`    ${r.key}: ${ty(r)}`);
      out.push('', '');
      out.push(`class ${name}(_${name}Required, total=False):`);
    } else out.push(`class ${name}(TypedDict, total=False):`);
    if (opt.length === 0) out.push('    pass');
    for (const o of opt) out.push(`    ${o.key}: ${o.text}`);
    out.push('', '');
  };

  out.push('"""GENERATED by tools/gen-sdk-models from src/lib/qbxml/spec.ts. Do not edit; run `npm run gen:sdk`.');
  out.push('', 'Request bodies are TypedDicts (camelCase keys, as the API takes them). Rows returned by the API are open:');
  out.push('a field QuickBooks adds is still in the dict at runtime even when the TypedDict does not name it."""');
  out.push('from __future__ import annotations', '');
  out.push('from typing import Any, Dict, List, TypedDict, Union', '');
  out.push('Number = Union[int, float, str]', '', '');
  emit('Ref', ref.map((f) => ({ key: keyOf(f), required: false, kind: f.kind, list: false })));
  emit('Address', address.map((f) => ({ key: keyOf(f), required: false, kind: f.kind, list: false })));
  for (const m of models()) {
    const cc = new Collector();
    collect(m.create, m.type, cc, false);
    for (const i of cc.ifaces.values()) emit(i.name, rows(i.fields, i.name, cc, { allOptional: false }));
    emit(`${m.type}Create`, rows(m.create, m.type, cc, { allOptional: false }));
    emit(m.type, rows(m.create, m.type, cc, { allOptional: true }), [{ key: 'listId', type: 'str' }, { key: 'txnId', type: 'str' }, { key: 'revisionNumber', type: 'str' }].filter((e) => e.key === m.idKey || e.key === 'revisionNumber'));
    if (m.update) {
      const cu = new Collector();
      const owner = `${m.type}Update`;
      collect(m.update, owner, cu, false);
      for (const i of cu.ifaces.values()) emit(i.name, rows(i.fields, i.name, cu, { allOptional: false }));
      emit(owner, rows(m.update, owner, cu, { allOptional: false, omit: [m.idKey] }));
    }
  }
  out.push('class NoUpdate(TypedDict, total=False):');
  out.push('    """Used for objects the API cannot update (payments): there is nothing to send."""', '', '');
  out.push('# URL segment -> model names. `updatable` is False where the API answers 405 not_supported.');
  out.push('MODELS: Dict[str, Dict[str, Any]] = {');
  for (const m of models()) out.push(`    "${m.object}": {"type": "${m.type}", "id_key": "${m.idKey}", "updatable": ${m.update ? 'True' : 'False'}},`);
  out.push('}');
  return `${out.join('\n')}\n`;
}
